for code in locales:
    file_path = f'src/locales/{code}.json'
    if not os.path.exists(file_path):
        print(f"Skipping {code}: file not found")
        continue
        
    try:
        with open(file_path, 'r', encoding='utf-8') as f:
            data = json.load(f)
            
        lang_trans = translations.get(code, translations['en'])
        
        # 1. Update common section
        if 'common' not in data:
            data['common'] = {}
        data['common']['yes'] = lang_trans['yes']
        data['common']['no'] = lang_trans['no']
        data['common']['reset'] = lang_trans['reset']
        data['common']['apply'] = lang_trans['apply']
        
        # 2. Update dashboard section
        if 'dashboard' not in data:
            data['dashboard'] = {}
            
        data['dashboard']['customizeTitle'] = lang_trans['customizeTitle']
        data['dashboard']['customizeSubtitle'] = lang_trans['customizeSubtitle']
        data['dashboard']['layoutType'] = lang_trans['layoutType']
        data['dashboard']['layoutGrid'] = lang_trans['layoutGrid']
        data['dashboard']['layoutList'] = lang_trans['layoutList']
        data['dashboard']['layoutGauge'] = lang_trans['layoutGauge']
        data['dashboard']['customizeButton'] = lang_trans['customizeButton']
        
        data['dashboard']['coolant'] = lang_trans['coolant']
        data['dashboard']['voltage'] = lang_trans['voltage']
        data['dashboard']['engineLoad'] = lang_trans['engineLoad']
        data['dashboard']['intakeAirTemp'] = lang_trans['intakeAirTemp']
        data['dashboard']['manifoldPressure'] = lang_trans['manifoldPressure']
        
        data['dashboard']['ambientTemp'] = lang_trans['ambientTemp']
        data['dashboard']['oilTemp'] = lang_trans['oilTemp']
        data['dashboard']['mafFlow'] = lang_trans['mafFlow']
        data['dashboard']['timingAdvance'] = lang_trans['timingAdvance']
        data['dashboard']['fuelLevel'] = lang_trans['fuelLevel']
        data['dashboard']['catalystTemp'] = lang_trans['catalystTemp']
        
        # Save back
        with open(file_path, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=4)
            
        print(f"Successfully synchronized language: {code}")
    except Exception as e:
        print(f"Error processing {code}: {e}")
