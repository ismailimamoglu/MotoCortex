/**
 * Cleans unwanted web-scraping artifacts from raw DTC descriptions.
 */
export function cleanDtcDescription(desc: string | null | undefined): string | null {
    if (!desc) return null;
    return desc
        .replace(/More details\.\.\./gi, '')
        .replace(/Read more\.\.\./gi, '')
        .replace(/\[\d+\]/g, '')
        .replace(/\(See P\d+\)/gi, '')
        .replace(/\s{2,}/g, ' ')
        .trim();
}

