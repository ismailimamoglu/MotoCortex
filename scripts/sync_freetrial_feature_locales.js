const languages = [
  'ar', 'cs', 'da', 'de', 'el', 'en', 'es', 'fi', 'fr', 'hi',
  'hu', 'id', 'it', 'ja', 'ko', 'nl', 'no', 'pl', 'pt', 'ro',
  'ru', 'sv', 'th', 'tr', 'uk', 'zh'
];

let updatedCount = 0;

for (const lang of languages) {
  const filePath = path.join(localesDir, `${lang}.json`);
  if (!fs.existsSync(filePath)) continue;

  const content = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  if (!content.features) {
    content.features = {};
  }

  for (const [key, langMap] of Object.entries(translations)) {
    const val = langMap[lang] || langMap['en'] || langMap['tr'];
    content.features[key] = val;
  }

  fs.writeFileSync(filePath, JSON.stringify(content, null, 4), 'utf8');
  updatedCount++;
}

console.log(`Successfully synced cleaned free trial keys (no emojis) across all ${updatedCount} languages!`);
