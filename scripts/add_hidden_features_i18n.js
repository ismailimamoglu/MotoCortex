const localeDir = path.join(__dirname, '../src/locales');
const files = fs.readdirSync(localeDir).filter(f => f.endsWith('.json'));

let updated = 0;
let skipped = 0;

for (const file of files) {
  const lang = file.replace('.json', '');
  const filePath = path.join(localeDir, file);
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  if (data.hiddenFeatures) {
    console.log(`⏭  ${lang} — already has hiddenFeatures, skipping`);
    skipped++;
    continue;
  }

  const t = translations[lang] || translations.en; // fallback to English
  data.hiddenFeatures = t;
  fs.writeFileSync(filePath, JSON.stringify(data, null, 4), 'utf8');
  console.log(`✅  ${lang} — hiddenFeatures added`);
  updated++;
}

console.log(`\nDone: ${updated} updated, ${skipped} skipped`);
